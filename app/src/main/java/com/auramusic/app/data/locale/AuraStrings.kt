    fun get(key: String, lang: String = "Español"): String {
        val code = when {
            lang.startsWith("English", ignoreCase = true) || lang == "en" -> "en"
            lang.startsWith("Português", ignoreCase = true) || lang == "pt" -> "pt"
            lang.startsWith("Français", ignoreCase = true) || lang == "fr" -> "fr"
            lang.startsWith("Deutsch", ignoreCase = true) || lang == "de" -> "de"
            lang.startsWith("日本語") || lang == "ja" -> "ja"
            else -> "es"
        }

        return translations[code]?.get(key) ?: translations["es"]?.get(key) ?: key
    }

