val LocalAuraStrings = staticCompositionLocalOf { EsStrings }

@Composable
fun ProvideAuraStrings(
    languageOption: AppLanguageOption,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val code = AppLanguage.resolvedCode(context, languageOption)
    val strings = when (code) {
        "en" -> EnStrings
        "pt" -> PtStrings
        "fr" -> FrStrings
        else -> EsStrings
    }
    CompositionLocalProvider(LocalAuraStrings provides strings, content = content)
}
